/**
 * Goodreads Sync Script
 * Fetches the "read" shelf RSS feed via rss2json and writes
 * formatted book data into src/data/books.js.
 *
 * Usage: npm run sync-books
 */

import { writeFileSync, readFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const GOODREADS_USER_ID = "203081565";
const SHELF = "read";
const PROFILE_URL = `https://www.goodreads.com/review/list/${GOODREADS_USER_ID}-waeijn?shelf=${SHELF}`;
const RSS_URL = `https://www.goodreads.com/review/list_rss/${GOODREADS_USER_ID}?shelf=${SHELF}`;
const API_URL = `https://api.rss2json.com/v1/api.json?rss_url=${encodeURIComponent(RSS_URL)}`;
const OUTPUT_PATH = resolve(__dirname, "../src/data/books.js");

/**
 * Parse author, rating, shelves, and review text from the RSS
 * description HTML string.
 */
function parseDescription(html) {
  const field = (name) => {
    const match = html.match(new RegExp(`(?:>|\\n)\\s*${name}:\\s*([^<\\n]+)`, "i"));
    return match ? match[1].trim() : "";
  };

  const reviewMatch = html.match(/review:\s*(?:<br>)?([\s\S]*?)$/);
  let review = "";
  if (reviewMatch) {
    review = reviewMatch[1]
      .replace(/<[^>]+>/g, "")
      .replace(/\\n/g, " ")
      .trim();
  }

  return {
    author: field("author"),
    rating: parseInt(field("rating"), 10) || 0,
    shelves: field("shelves"),
    review,
  };
}

/**
 * Upgrade the tiny _SY75_ / _SX50_ thumbnail to a larger _SY180_ cover.
 */
function upgradeCover(thumbUrl) {
  return thumbUrl
    .replace(/\._SY\d+_\./, "._SY180_.")
    .replace(/\._SX\d+_\./, "._SY180_.");
}

/**
 * Extract the Goodreads review ID from a review link URL.
 */
function extractReviewId(link) {
  const match = link.match(/review\/show\/(\d+)/);
  return match ? match[1] : "";
}

async function main() {
  console.log("📚 Fetching Goodreads RSS feed...");

  // Try to load existing books to preserve manually added tags
  let existingTags = {};
  try {
    const existingContent = readFileSync(OUTPUT_PATH, "utf-8");
    // Extract the JSON array from the file using regex or eval
    const match = existingContent.match(/export const BOOKS = (\[[\s\S]*?\]);/);
    if (match) {
      const existingBooks = JSON.parse(match[1]);
      existingBooks.forEach((b) => {
        if (b.tag) existingTags[b.id] = b.tag;
      });
    }
  } catch (e) {
    console.log("   No existing books.js found or couldn't parse it. Starting fresh.");
  }

  const res = await fetch(API_URL);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status}: ${res.statusText}`);
  }

  const data = await res.json();
  if (data.status !== "ok") {
    throw new Error(`rss2json error: ${JSON.stringify(data)}`);
  }

  console.log(`   Found ${data.items.length} books on the "${SHELF}" shelf.`);

  const books = data.items.map((item) => {
    const parsed = parseDescription(item.description || "");
    const reviewId = extractReviewId(item.link || "");

    const book = {
      id: reviewId,
      title: item.title,
      author: parsed.author,
      rating: parsed.rating,
    };

    // Use Goodreads shelf if available, otherwise fallback to existing local tag
    if (parsed.shelves) {
      book.tag = parsed.shelves;
    } else if (existingTags[reviewId]) {
      book.tag = existingTags[reviewId];
    }

    book.cover = upgradeCover(item.thumbnail || "");
    book.link = `https://www.goodreads.com/review/show/${reviewId}`;

    if (parsed.review) {
      book.review = parsed.review;
    }

    return book;
  });

  // Sort: highest rating first, then by title
  books.sort((a, b) => b.rating - a.rating || a.title.localeCompare(b.title));

  const output = `// src/data/books.js
// Auto-generated by scripts/sync-goodreads.js \u2014 do not edit manually.
// Last synced: ${new Date().toISOString()}

export const GOODREADS_PROFILE_URL =
  ${JSON.stringify(PROFILE_URL)};

export const BOOKS = ${JSON.stringify(books, null, 2)};
`;

  writeFileSync(OUTPUT_PATH, output, "utf-8");
  console.log(`\u2705 Wrote ${books.length} books to src/data/books.js`);
}

main().catch((err) => {
  console.error("\u274C Sync failed:", err.message);
  process.exit(1);
});
